export function getResult(fixture) {
  if (fixture.status !== 'completed' || fixture.homeScore === undefined || fixture.awayScore === undefined) return null;
  const isHome = fixture.homeTeam === 'Mphehli All Stars';
  const mphehliScore = isHome ? fixture.homeScore : fixture.awayScore;
  const opponentScore = isHome ? fixture.awayScore : fixture.homeScore;
  if (mphehliScore > opponentScore) return 'WIN';
  if (mphehliScore === opponentScore) return 'DRAW';
  return 'LOSS';
}

export function getOpponent(fixture) {
  return fixture.homeTeam === 'Mphehli All Stars' ? fixture.awayTeam : fixture.homeTeam;
}

export function getClubStats() {
  const completed = fixtures.filter(f => f.status === 'completed');
  const wins = completed.filter(f => getResult(f) === 'WIN').length;
  const draws = completed.filter(f => getResult(f) === 'DRAW').length;
  const losses = completed.filter(f => getResult(f) === 'LOSS').length;
  const goals = completed.reduce((sum, f) => {
    if (f.homeScore === undefined || f.awayScore === undefined) return sum;
    return sum + (f.homeTeam === 'Mphehli All Stars' ? f.homeScore : f.awayScore);
  }, 0);
  return {
    matches: completed.length,
    wins,
    draws,
    losses,
    goals,
    players: players.filter(p => p.status === 'active').length,
    followers: 18,
  };
}
